// Turns src/tokens/tokens.json into CSS custom properties.
// Primitives hold raw values; components use only semantic tokens, which point at primitives.
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../src/tokens/tokens.json', import.meta.url);
const out = new URL('../src/tokens/tokens.css', import.meta.url);
const t = JSON.parse(readFileSync(src, 'utf8'));
const name = (s) => s.replace(/[/.]/g, '-');
const lines = ['/* Generated by scripts/build-tokens.mjs from tokens.json – do not edit by hand */', ':root {'];

for (const [k, v] of Object.entries(t.primitives.color)) lines.push(`  --color-${k}: ${v};`);
for (const [k, v] of Object.entries(t.primitives.spacing)) lines.push(`  --spacing-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.primitives.radius)) lines.push(`  --radius-${k}: ${v}px;`);
lines.push('');
for (const [k, v] of Object.entries(t.semantic)) {
  const ref = v.match(/^\{(.+)\}$/);
  lines.push(`  --${name(k)}: ${ref ? `var(--${name(ref[1])})` : v};`);
}
lines.push('', '  --font-family: "Inter", system-ui, -apple-system, sans-serif;');
for (const [k, s] of Object.entries(t.typography)) {
  const n = name(k);
  lines.push(`  --${n}-weight: ${s.weight};`, `  --${n}-size: ${s.size}px;`, `  --${n}-line-height: ${s.lineHeight};`, `  --${n}-letter-spacing: ${s.letterSpacing};`);
}
lines.push('}', '');
for (const k of Object.keys(t.typography)) {
  const n = name(k);
  lines.push(`.text-${n} { font-family: var(--font-family); font-weight: var(--${n}-weight); font-size: var(--${n}-size); line-height: var(--${n}-line-height); letter-spacing: var(--${n}-letter-spacing); }`);
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`tokens.css: ${Object.keys(t.semantic).length} semantic tokens`);
